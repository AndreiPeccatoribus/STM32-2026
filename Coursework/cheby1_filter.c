/* cheby1_filter.c */
#include "cheby1_filter.h"

typedef struct {
    float b0, b1, b2;   /* коэффициенты числителя */
    float a1, a2;       /* коэффициенты знаменателя (a0 = 1) */
    float d1, d2;       /* ячейки памяти: v[n-1] и v[n-2] */
} Biquad;

/* Коэффициенты из таблицы 3.
   Множитель K = 0.9441 входит в b0, b1, b2 первого звена */
static Biquad sections[3] = {
    { 0.0033401923f, 0.0066803845f, 0.0033401923f,
      -1.8195327f, 0.83368454f, 0.0f, 0.0f },
    { 0.013462937f, 0.026925873f, 0.013462937f,
      -1.8228601f, 0.87671181f, 0.0f, 0.0f },
    { 0.024049584f, 0.048099169f, 0.024049584f,
      -1.8573205f, 0.95351889f, 0.0f, 0.0f }
};

float cheby1_filter(float input)
{
    float y = input;                               /* вход первого звена */
    for (int i = 0; i < 3; i++) {
        Biquad *s = &sections[i];
        float v = y - s->a1 * s->d1 - s->a2 * s->d2;   /* v[n] */
        y = s->b0 * v + s->b1 * s->d1 + s->b2 * s->d2; /* выход звена */
        s->d2 = s->d1;                             /* сдвиг ячеек памяти */
        s->d1 = v;
    }
    return y;                                      /* выход последнего звена */
}